def sum_of_number(number_one, number_two):
      return number_one + number_two
      
def subtract_of_number(number_one, number_two):
      return number_one - number_two
      
def multiple_of_number(number_one, number_two):
      return number_one * number_two
      
def divide_of_number(number_one, number_two):
      return number_one / number_two
      
print(sum_of_number(45, 23))
print(subtract_of_number(76, 45))
print(multiple_of_number(65, 43))
print(divide_of_number(78, 2))
